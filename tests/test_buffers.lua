local origin = vim.api.nvim_get_current_buf()
local saved = vim.fn.maparg('dd', 'n', false, true)
vim.fn.maparg('<leader>fb', 'n', false, true).callback()
local prompt = vim.api.nvim_get_current_buf()
assert(prompt ~= origin and vim.bo[prompt].buftype == 'prompt')
local mapping = vim.fn.maparg('dd', 'n', false, true)
assert(type(mapping.callback) == 'function', 'Buffer picker dd must invoke the delete action')
require('telescope.actions').close(prompt)
assert(vim.deep_equal(saved, vim.fn.maparg('dd', 'n', false, true)), 'Picker leaked its dd mapping')
