local terms = require('toggleterm.terminal')
vim.cmd('3T')
assert(terms.get_focused_id() == 3)
vim.cmd('7T')
assert(terms.get_focused_id() == 7)
local function press(lhs)
  local map = vim.fn.maparg(lhs, 'n', false, true)
  assert(type(map.callback) == 'function', 'Missing terminal mapping: ' .. lhs)
  map.callback()
end
press('gt')
assert(terms.get_focused_id() == 3, 'gt should wrap across non-contiguous terminal IDs')
press('gT')
assert(terms.get_focused_id() == 7)
vim.cmd('7T')
assert(terms.get_focused_id() == nil, 'T with the focused ID should hide it')
vim.cmd('3T')
press('<C-T>')
assert(terms.get_focused_id() == 1, 'Ctrl-T should create the next free ID')
for _, term in ipairs(terms.get_all()) do term:shutdown() end
